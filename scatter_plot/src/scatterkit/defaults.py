"""EVERY default of the scatter plot lives in this file -- tweak them here.

Each ``P(name, default, kind, help)`` line is one parameter. The same name is
the key in a config file (``name=value``, one per line) and the attribute on a
``Style`` object. Nothing else in the package hard-codes a visual choice, with
one deliberate exception: the font, which is fixed just below.

Lengths: figure geometry is in inches, line widths / tick lengths / font sizes /
paddings are in points, marker sizes are areas in points^2 (matplotlib's ``s``).
Colours: any matplotlib colour (name, #rrggbb, 0.5 for a grey) or ``none``.
``auto`` (None here) means "work it out while drawing"; the help says how.
"""

